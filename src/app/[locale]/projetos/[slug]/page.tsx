import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import type { ReactNode } from "react";
import Header from "@/components/header";
import { ArrowLeftIcon, ArrowRightIcon, ArrowUpRightIcon, GithubIcon } from "@/components/icons";
import ProjectImage from "@/components/project-image";
import Reveal from "@/components/reveal";
import { getProject, profile, projects, skillLabels } from "@/data/portfolio";
import { isLocale } from "@/i18n/config";
import { getDictionary } from "@/i18n/dictionaries";
import { notFoundMetadata } from "@/lib/not-found";
import { localePath, ogImagePath, projectsPath, sections, shareMetadata } from "@/lib/site";

// Only the slugs in `src/data/portfolio.ts` exist; anything else is a 404.
export const dynamicParams = false;

/** Runs once per locale generated by the layout, so it only fills `slug`. */
export function generateStaticParams() {
  return projects.map((project) => ({ slug: project.slug }));
}

export async function generateMetadata({
  params,
}: PageProps<"/[locale]/projetos/[slug]">): Promise<Metadata> {
  const { locale, slug } = await params;
  const project = getProject(slug);

  if (!isLocale(locale)) {
    return {};
  }
  if (!project) {
    return notFoundMetadata(locale);
  }

  const copy = getDictionary(locale).projects.items[project.slug];
  const path = `${projectsPath}/${project.slug}`;

  return {
    title: copy.title,
    description: copy.summary,
    ...shareMetadata(locale, {
      path,
      title: `${copy.title} | ${profile.name}`,
      description: copy.summary,
      image: { url: ogImagePath(locale, path), alt: `${copy.title}: ${copy.tagline}` },
    }),
  };
}

// `max-w-5xl` minus the horizontal padding.
const contentSizes = "(min-width: 1024px) 976px, calc(100vw - 2rem)";

const cardClass =
  "rounded-2xl border border-black/10 bg-white/60 dark:border-white/10 dark:bg-white/5";

const buttonClass =
  "inline-flex items-center gap-2 rounded-full border border-black/15 px-5 py-2.5 text-sm font-semibold transition-all hover:-translate-y-0.5 hover:border-violet-400/60 hover:bg-black/5 dark:border-white/15 dark:hover:border-violet-400/40 dark:hover:bg-white/10";

function Block({ title, children }: { title: string; children: ReactNode }) {
  return (
    <Reveal>
      <section>
        <h2 className="font-pixel text-sm text-violet-600 dark:text-violet-400">{title}</h2>
        <div className="mt-3 text-foreground/80">{children}</div>
      </section>
    </Reveal>
  );
}

export default async function ProjectPage({ params }: PageProps<"/[locale]/projetos/[slug]">) {
  const { locale, slug } = await params;
  const project = getProject(slug);

  if (!isLocale(locale) || !project) {
    notFound();
  }

  const dictionary = getDictionary(locale);
  const { caseStudy } = dictionary;
  const copy = dictionary.projects.items[project.slug];

  const index = projects.indexOf(project);
  const next = projects[(index + 1) % projects.length];
  const nextCopy = dictionary.projects.items[next.slug];

  const facts = [
    { id: "year", label: caseStudy.year, value: project.year },
    ...project.stats.map((stat) => ({ id: stat.id, label: copy.stats[stat.id], value: stat.value })),
  ];

  return (
    <>
      <Header
        locale={locale}
        name={profile.name}
        navigation={dictionary.navigation}
        theme={dictionary.theme}
        paletteLabel={dictionary.palette.open}
      />
      <main id="content" className="mx-auto w-full max-w-5xl px-4 pt-24 pb-24 sm:px-6 sm:pt-32">
        <Link
          href={`${localePath(locale)}#${sections.projects}`}
          className="inline-flex items-center gap-2 text-sm font-semibold text-foreground/70 transition-colors hover:text-violet-600 dark:hover:text-violet-400"
        >
          <ArrowLeftIcon className="size-4" />
          {caseStudy.back}
        </Link>

        <article className="mt-8">
          <header>
            <p className="font-pixel text-sm text-foreground/50">
              {project.kind} · {project.year}
            </p>
            <h1 className="mt-3 text-4xl font-bold tracking-tight sm:text-5xl">{copy.title}</h1>
            <p className="mt-4 text-xl font-semibold text-violet-600 sm:text-2xl dark:text-violet-400">
              {copy.tagline}
            </p>
            <p className="mt-5 max-w-3xl text-lg leading-relaxed text-foreground/70">
              {copy.summary}
            </p>
            <div className="mt-8 flex flex-wrap gap-3">
              <a
                href={project.repository}
                target="_blank"
                rel="noopener noreferrer"
                className={buttonClass}
              >
                <GithubIcon className="size-4" />
                {dictionary.projects.repository}
              </a>
              {project.live && (
                <a
                  href={project.live}
                  target="_blank"
                  rel="noopener noreferrer"
                  className={buttonClass}
                >
                  <ArrowUpRightIcon className="size-4" />
                  {dictionary.projects.live}
                </a>
              )}
            </div>
          </header>

          <div className={`mt-12 overflow-hidden ${cardClass}`}>
            <ProjectImage
              image={project.cover}
              alt={copy.imageAlt}
              sizes={contentSizes}
              priority
              className="h-auto w-full"
            />
          </div>

          <div className="mt-16 grid gap-12 lg:grid-cols-[1.5fr_1fr] lg:gap-16">
            <div className="space-y-12">
              <Block title={caseStudy.problem}>
                <p className="leading-relaxed">{copy.problem}</p>
              </Block>
              <Block title={caseStudy.role}>
                <p className="leading-relaxed">{copy.role}</p>
              </Block>
              <Block title={caseStudy.highlights}>
                <ul className="space-y-2.5">
                  {copy.highlights.map((highlight) => (
                    <li key={highlight} className="flex gap-3">
                      <span aria-hidden="true" className="mt-2.5 size-1.5 shrink-0 bg-violet-500" />
                      <span className="leading-relaxed">{highlight}</span>
                    </li>
                  ))}
                </ul>
              </Block>
              <Block title={caseStudy.outcome}>
                <p className="leading-relaxed">{copy.outcome}</p>
              </Block>
            </div>

            <aside className="lg:sticky lg:top-24 lg:self-start">
              <Reveal delay={150}>
                <div className={`p-6 ${cardClass}`}>
                  <h2 className="font-pixel text-sm text-foreground/50">{caseStudy.facts}</h2>
                  <dl className="mt-4 font-mono text-sm">
                    {facts.map((fact) => (
                      <div key={fact.id} className="flex items-baseline gap-2 py-1.5">
                        <dt className="flex min-w-0 flex-1 items-baseline gap-2 text-violet-600 lowercase dark:text-violet-400">
                          {fact.label}
                          <span
                            aria-hidden="true"
                            className="min-w-4 flex-1 translate-y-[-3px] border-b border-dotted border-foreground/25"
                          />
                        </dt>
                        <dd className="text-right text-foreground/85">{fact.value}</dd>
                      </div>
                    ))}
                  </dl>

                  <h2 className="mt-8 font-pixel text-sm text-foreground/50">{caseStudy.stack}</h2>
                  <ul className="mt-4 flex flex-wrap gap-2">
                    {project.skills.map((skill) => (
                      <li
                        key={skill}
                        className="rounded-full bg-black/5 px-3 py-1 text-xs font-medium text-foreground/80 dark:bg-white/10"
                      >
                        {skillLabels[skill]}
                      </li>
                    ))}
                  </ul>
                </div>
              </Reveal>
            </aside>
          </div>

          {project.gallery.length > 0 && (
            <section className="mt-20">
              <Reveal>
                <h2 className="font-pixel text-sm text-violet-600 dark:text-violet-400">
                  {caseStudy.gallery}
                </h2>
              </Reveal>
              <div
                className={`mt-6 grid gap-6 ${project.gallery.length > 1 ? "sm:grid-cols-2" : ""}`}
              >
                {project.gallery.map((image, position) => (
                  <Reveal key={image.light.src} delay={position * 80} className="h-full">
                    <figure
                      className={`flex h-full items-center justify-center p-4 sm:p-6 ${cardClass}`}
                    >
                      <ProjectImage
                        image={image}
                        alt={copy.galleryAlts[position] ?? copy.imageAlt}
                        sizes={
                          project.gallery.length > 1
                            ? "(min-width: 640px) 50vw, calc(100vw - 2rem)"
                            : contentSizes
                        }
                        className="h-auto max-h-[36rem] w-auto max-w-full rounded-lg"
                      />
                    </figure>
                  </Reveal>
                ))}
              </div>
            </section>
          )}
        </article>

        <nav aria-label={caseStudy.next} className="mt-20">
          <Reveal>
            <Link
              href={localePath(locale, `${projectsPath}/${next.slug}`)}
              className={`group flex items-center justify-between gap-6 p-6 transition-all hover:-translate-y-0.5 hover:border-violet-400/60 sm:p-8 dark:hover:border-violet-400/40 ${cardClass}`}
            >
              <span>
                <span className="block font-pixel text-sm text-foreground/50">
                  {caseStudy.next}
                </span>
                <span className="mt-2 block text-2xl font-bold tracking-tight">
                  {nextCopy.title}
                </span>
                <span className="mt-1 block text-foreground/70">{nextCopy.tagline}</span>
              </span>
              <ArrowRightIcon className="size-6 shrink-0 text-violet-500 transition-transform group-hover:translate-x-1" />
            </Link>
          </Reveal>
        </nav>
      </main>
    </>
  );
}
